export function buildCreativePackagingPrompt({ domain, audience, idea }) {
  const domainText = domain && domain.trim() ? domain.trim() : '[התחום שלי]';
  const audienceText = audience && audience.trim() ? audience.trim() : '[הקהל שלי]';
  return `התחום שלי זה: ${domainText}
קהל היעד שלי זה: ${audienceText}
זה הרעיון שלי לתוכן והמסר: ${idea}
אני רוצה שתמצא לי 30 פורמטי הנגשה מעניינים ולא בנאליים, לסרטון הזה לרשתות החברתיות, מאוד מיוחדים/מושכים תשומת לב/מקוריים/חכמים וממירים. אני רוצה שהפורמטי הנגשה יהיו מגוונים, לא רק דיבור למצלמה (גם) אבל גם בירול עם טקסט, פוסט קרוסלה, ראיון/שיחה עם מישהו, וויס אובר ועוד כל מיני מגוונים. תחשוב על דברים וואוווו`;
}
