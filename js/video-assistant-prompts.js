export function buildDuplicationPrompt({ audience, domain, hook }) {
  const audienceText = audience && audience.trim() ? audience.trim() : '[הקהל שלי]';
  const domainText = domain && domain.trim() ? domain.trim() : '[התחום שלי]';
  return `הקהל יעד העיקרי שלי הוא: ${audienceText}
התחום שלי הוא: ${domainText}
אני רוצה שתקח את ההוק הזה: ${hook}
ובעצם תשכפל אותו בול 1:1, אותו מנגנון 1:1, אותו אורך, אותו מבנה רק מותאם
לעולם ולקהל שלי ותביא לי עוד 30 רעיונות חזקים אבל תזכור בול לשכפל מגנון
1:1 ואותו אורך! שים לב מדויק לכל הדגשים שכתבתי ומותאם לקהל יעד שלי בול`;
}

// 19/10/2026 (מאיה, גרסה שלישית - "הסדר בשכפול ההפוך לא טוב", שלחה את
// הניסוח המדויק הסופי): שכפול הפוך שונה משכפול רגיל - יש כבר תסריט/
// מגילת אסתר משלה (state.herWords, נכתב אחרי שההוק כבר זוהה מהרפרנס)
// לפני שמבקשים הוקים, ו-ChatGPT שולף הוקים חזקים *מתוך התסריט שלה* ומלביש
// אותם על מנגנון ההוק המקורי - לא ניסוח buildDuplicationPrompt למעלה (זה
// לשכפול רגיל, בלי תסריט קונקרטי עדיין). כולל גם קהל יעד (audience),
// בניגוד לגרסה הקודמת שהייתה רק תחום.
//
// 19/10/2026 (מאיה: "בואי למחוק מהפורמט שהוא ימליץ לי על 3 הכי טובים כי
// הוא ממליץ גרוע") - גם אחרי שחידדתי את קריטריוני הבחירה (ראה גרסה
// קודמת), ההמלצה על 3 מתוך ה-30 נשארה גרועה - הוסרה לגמרי, היא עוברת
// ידנית על כל ה-30.
export function buildReverseDuplicationPrompt({ domain, audience, hook, script }) {
  const domainText = domain && domain.trim() ? domain.trim() : '[התחום שלי]';
  const audienceText = audience && audience.trim() ? audience.trim() : '[הקהל יעד שלי]';
  return `התחום שלי הוא: ${domainText}
הקהל יעד שלי הוא: ${audienceText}
זה ההוק שאני רוצה לשכפל בול 1:1 אותו מנגנון אותו אורך אותו מבנה אליי: ${hook}
וזה בעצם התסריט שלי שממנו אני רוצה שתשלוף את ההוקים החזקים ותלביש את זה בול 1:1 אותו מנגנון אותו אורך אותו מבנה על ההוק המקורי שצירפתי לך ותביא לי 30 רעיונות חזקים:
${script}
שים לב שהוק חייב להיות ברור, כמה שיותר ספציפי, מעורר רגש או מסקרן !!!!! אסור שיהיה סיסמתי, הוא צריך להתאים לרשתות החברתיות אבל כמובן שמתי לב הוק מקורי של סרטון שכבר עבד אז אתה משכפל בול את המגננון אבל השכפול חייב להיות מדויק, להיצמד לאותו אורך ואותו מבנה רק מותאם אליי`;
}

// 19/10/2026 (מאיה, אחרי אישור מפורש): נוסף שדה "התסריט המקורי" - עד
// עכשיו הפרומפט הזה הניח ש-ChatGPT "זוכר" את התסריט המקורי מהפרומפט
// הקודם באותה שיחה, בדיוק כמו שהמתודולוגיה שלה בשלב 10 מראה ("1. התסריט
// המקורי. 2. ההוק המשוכפל שלנו. 3. מגילת אסתר" - שלושתם מודבקים מפורשות,
// לא בהסתמכות על זיכרון שיחה). זה גם תיקן תקלה אמיתית: מאז שפרומפט 1
// הפסיק לשלוח את כל התמלול (19/10, extractOpeningHook) ושולח רק את ההוק
// שחולץ, ל-ChatGPT כבר לא היה "תסריט מקורי" בהקשר השיחה בכלל עד עכשיו.
export function buildScriptPrompt({ hook, herWords, originalScript }) {
  return `התסריט המקורי: ${originalScript}
זה ההוק שבחרתי: ${hook}
זה מה שיש לי להגיד: ${herWords}
אני רוצה עכשיו שתקח את ההוק שלי תלביש אותו בתסריט המקורי יחד עם כל מה
שיש לי להגיד אבל הכי חשוב? תשמור על מנגנון התסריט 1:1, את האורך אותו
אורך, אל תעשה יותר ארוך, אותו מבנה, אותו מנגנון רק הכל מותאם לקהל שלי
ולהוק שלי!!`;
}
