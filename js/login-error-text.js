// עד עכשיו קוד השגיאה הגולמי של Firebase (באנגלית) הוצג ישירות למשתמשת -
// למשל "ההתחברות נכשלה: auth/network-request-failed" - זה היה מכוון בזמנו
// (ראו ההיסטוריה בקוד שקורא לפונקציה הזו) כדי שכשל אמיתי לא ייראה כמו
// "שום דבר לא קרה", אבל זה גם לא מובן לרוב המשתמשות. השורה הזו ממפה את
// הקודים הנפוצים לעברית ברורה, עם console.error שעדיין שומר את הקוד המקורי
// לצורך דיבוג - כך שהמידע לא הולך לאיבוד, רק לא מוצג גולמי על המסך.
const KNOWN_LOGIN_ERRORS = {
  'auth/network-request-failed': 'בעיית רשת - בדקו חיבור לאינטרנט ונסו שוב.',
  'auth/too-many-requests': 'יותר מדי ניסיונות - נסו שוב בעוד כמה דקות.',
  'auth/user-disabled': 'החשבון הזה חסום, פנו למאיה.',
  'auth/internal-error': 'שגיאה פנימית, נסו שוב בעוד רגע.',
  'auth/unauthorized-domain': 'האתר הזה לא מורשה להתחברות כרגע, פנו למאיה.',
};

export function loginErrorText(err) {
  return KNOWN_LOGIN_ERRORS[err && err.code] || 'ההתחברות נכשלה, נסו שוב או פנו למאיה.';
}
