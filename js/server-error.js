/**
 * הודעה ללקוחה על כישלון קריאה לשרת.
 *
 * 12/10/2026: כאן ישב "החיבור נכשל, כנראה בגלל רשת לא יציבה" לכל שגיאה
 * שאינה בעברית. אבל כל כישלון שאינו מהשרת שלנו נראה בדיוק כך: חיוב
 * מנותק, פונקציה שלא נפרסה, CORS, DNS, או 5xx לפני גוף התשובה. כלומר
 * תקלת שרת הוצגה ללקוחה כבעיה ברשת שלה, והיא ניסתה מחיבור אחר במקום
 * לספר למאיה. זה קרה באמת ב-11/10 לאורך כל היום.
 *
 * ההבחנה: TypeError מ-fetch פירושו שהדפדפן לא קיבל תשובה בכלל. אם
 * הדפדפן מדווח שהוא לא מחובר, זאת באמת הרשת. אחרת זה אצלנו.
 */
export function serverErrorText(err, what, opts = {}) {
  const msg = String((err && err.message) || '');
  if (/[֐-׿]/.test(msg)) return `משהו השתבש ב${what}: ${msg}. נסו שוב.`;
  /* online נמסר במפורש רק בבדיקות: אי אפשר לדרוס את navigator ב-node */
  const online = opts.online !== undefined
    ? opts.online
    : (typeof navigator === 'undefined' ? true : navigator.onLine !== false);
  if (!online) {
    return 'אין חיבור לאינטרנט כרגע. נסו שוב כשהחיבור חוזר.';
  }
  return 'השרת לא זמין כרגע. זאת תקלה אצלנו ולא אצלכם, כדאי לנסות שוב בעוד רגע.';
}
