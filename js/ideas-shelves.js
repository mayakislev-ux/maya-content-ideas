/* רעיון שאין לו אחד משלושת הסוגים: טיוטה שעוד לא סווגה, או רעיון ישן
   שנשאר מתויג "בידורי". הוא נכנס לכניסה רביעית שקטה ולא נעלם. */
export const UNSORTED_GROUP = '__none__';

/** לאיזה כפתור הרעיון שייך. "ערכי" הוא השם הישן של "בעל ערך". */
export function groupKeyFor(idea) {
  const c = idea ? idea.category : '';
  if (c === 'ערכי') return 'בעל ערך';
  return CATEGORIES.includes(c) ? c : UNSORTED_GROUP;
}

/** { 'בעל ערך': [], 'אישי': [], 'מכירתי': [], __none__: [] }, והסדר
    שהגיע (המיון שנבחר במסך) נשמר בתוך כל קבוצה. */
export function groupByCategory(ideas) {
  const out = { [UNSORTED_GROUP]: [] };
  for (const g of CATEGORY_GROUPS) out[g.id] = [];
  for (const idea of ideas || []) out[groupKeyFor(idea)].push(idea);
  return out;
}

/** "רעיון אחד" / "3 רעיונות" */
export function ideasCountLabel(n) {
  return n === 1 ? 'רעיון אחד' : `${n} רעיונות`;
}
