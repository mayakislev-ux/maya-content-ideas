const FORMAT_NAMES = FORMAT_GUIDE.map(([n]) => n);

function buildFormatRecommendPrompt({ idea, message, angle, startingPoint, packaging }) {
  const lines = [];
  if (idea) lines.push(`הרעיון: ${idea}`);
  if (message) lines.push(`המסר שהיא רוצה שיבינו: ${message}`);
  if (angle) lines.push(`זווית ההנגשה: ${angle}`);
  if (startingPoint) lines.push(`נקודת היציאה: ${startingPoint}`);
  lines.push(`האריזה הקריאייטיבית שנבחרה: ${packaging}`);

  return `את יועצת תוכן לבעלת עסק שמצלמת רילס לאינסטגרם. היא כבר בחרה רעיון ואריזה קריאייטיבית, ועכשיו צריך להמליץ לה באיזה פורמט לצלם.

${lines.join('\n')}

הפורמטים האפשריים (רק מהרשימה הזו, בדיוק בשמות האלה):
${FORMAT_GUIDE.map(([n, d]) => `- ${n}: ${d}`).join('\n')}

איך מחליטים (תחשבי על הסרטון כולו, לא על מילה בודדת באריזה):
1. מה מחזיק את הסרטון? אם זה הסיפור, הדעה, הטיעון או הניסיון שלה, היא צריכה להיות על המסך ולדבר. דיבור למצלמה הוא כמעט תמיד הבחירה הראשונה לסיפור אישי, דעה, ביקורת, טעות נפוצה, מחיר, תובנה עסקית או מסר שצריך לשכנע.
2. ראיון / שיחה חזק כשיש טיעון שאפשר לפתוח בשאלה ("למה לא העלית מחיר?"), או כשהמסר מתבהר בדיאלוג. ברעיון של דעה, סיפור אישי או טיעון עסקי, הוא הבחירה השנייה אחרי דיבור למצלמה.
3. אם באריזה רואים אותה מול המצלמה (מחזיקה משהו, מסתכלת למצלמה, הבעת פנים, שואלת את הצופים), היא מדברת למצלמה, גם אם כתוב שם "קריינות" או "קול".
4. וויס אובר רק כשהסרטון בנוי מסצנות שבהן לא רואים אותה מדברת והתמונה מספרת את הסיפור. לא בוחרים בו בגלל מילה כמו "קריינות".
5. טקסט דינמי ותוכן ויזואלי יפה רק כשהרעיון עובר דרך התמונה ולא דרך טיעון.
6. משחק תפקידים רק כשהאריזה עצמה מביימת שתי דמויות (POV, דיאלוג, לקוחה מול בעלת עסק). רעיון של "הטעות מול הדרך הנכונה" לבד לא מספיק בשביל משחק תפקידים. תגובה לתגובה וסטיץ' רק כשיש באמת תגובה או סרטון להגיב אליהם. פוסט קרוסלה רק אם האריזה היא שקופיות.
7. לא ממליצים על פורמט שרק "יכול לעבוד", ולא מוסיפים פורמט כדי להגיע למספר. מה שהאריזה אומרת קובע: אם כתוב "בלי לדבר" או "בלי דיבור", לא ממליצים על פורמט שיש בו את הקול או הדיבור שלה (לא וויס אובר ולא דיבור למצלמה).

תני 2 או 3 פורמטים, מהכי מתאים למטה. שלישי רק אם הוא באמת מתאים באותה מידה. לכל אחד נימוק של משפט אחד קצר, עד 15 מילים, בעברית פשוטה, שמדבר על הרעיון הזה ספציפית (לא הגדרה כללית של הפורמט). הנימוק לא מדבר עליה בגוף שלישי ("היא", "שלה") ולא פונה אליה בלשון זכר או נקבה, למשל: "טיעון על מחיר משכנע הכי הרבה כשרואים את הפנים שאומרות אותו". בלי מקף ארוך.

השיבי רק ב-JSON תקין, בלי שום טקסט נוסף:
{"picks":[{"name":"<שם פורמט מהרשימה>","why":"<משפט אחד>"}]}`;
}

/** מנקה את תשובת המודל: רק שמות מהרשימה, בלי כפולים, 1-3, ונימוק קצר. */
function parseFormatPicks(text) {
  let parsed;
  try {
    const m = String(text || '').match(/\{[\s\S]*\}/);
    parsed = JSON.parse(m ? m[0] : text);
  } catch (e) {
    return [];
  }
  const seen = new Set();
  const out = [];
  for (const p of (parsed && Array.isArray(parsed.picks) ? parsed.picks : [])) {
    const name = String((p && p.name) || '').trim();
    if (!FORMAT_NAMES.includes(name) || seen.has(name)) continue;
    seen.add(name);
    out.push({ name, why: String((p && p.why) || '').replace(/\s*[—–]\s*/g, ', ').trim().slice(0, 220) });
    if (out.length === 3) break;
  }
  return out;
}

