const SCREEN_HINT = {
  'idea-sharpen': 'חידוד הרעיון לסרטון',
  'type-idea': 'כתיבת הרעיון לסרטון',
  transcribe: 'הדבקת התמלול של סרטון רפרנס',
  'content-basics': 'הבסיס של התוכן (מה רוצים להגיד ולמי)',
  'footage-speech-sharpen': 'חידוד מה שנאמר בחומר המצולם',
  'scratch-distill': 'זיקוק המסר מתוך מה שנכתב',
  prompt2: 'עבודה על התסריט',
  'scratch-dump': 'מגילה: לשפוך את כל מה שיש להגיד על הרעיון',
  'her-words': 'מגילה: כל מה שיש להגיד על הרעיון, במילים של בעל העסק',
};

function pronounLine(pronoun) {
  if (pronoun === 'את') return 'פני אליה בלשון נקבה (את).';
  if (pronoun === 'אתה') return 'פני אליו בלשון זכר (אתה).';
  return 'אל תניחי מגדר: נסחי בלי פנייה מגדרית (למשל "שווה לחדד", "יאללה מחדדים", לשון רבים או שם פועל).';
}

function buildMayaNotePrompt({ screen, text, domain, pronoun }) {
  return `את מאיה קיסלב, מנטורית לשיווק בתוכן ולסרטונים קצרים. לקוח או לקוחה שלך כותבים עכשיו בעוזר ליצירת סרטון, בשלב: ${SCREEN_HINT[screen] || 'כתיבה לסרטון'}.${domain ? `\nהתחום של העסק: ${domain}` : ''}

מה שנכתב עד עכשיו:
"""
${text}
"""

תני הערה אחת בלבד, כמו שהיית אומרת תוך כדי, בהודעה קולית מהירה:
 • משהו אחד ספציפי שראית בטקסט הזה: המשפט הכי חזק שקבור באמצע ("זה ההוק שלך! למה הוא באמצע?"), מקום כללי מדי שצריך מספר או דוגמה אמיתית, או פרט מעולה שצריך להבליט. לא מחמאה כללית ולא סיכום.
 • אם יש משפט חזק, צטטי ממנו כמה מילים במירכאות.
 • בקול שלך: חם, ישיר, קצת מוגזם. מותר "רגע", "יאללה", "וואו", "עף לי על הראש", "תני בראש" / "תן בראש", אות מתארכת להדגשה ("טירוףףף"), אבל לא בכל משפט.
 • עד 22 מילים. בלי קו מפריד ארוך (—). בלי רשימות. בלי הקדמה. אימוג'י אחד לכל היותר.
 • ${pronounLine(pronoun)}

כתבי רק את ההערה עצמה.`;
}

/** ניקוי התשובה: שורה אחת, בלי מירכאות עוטפות, בלי קו ארוך, עד 200 תווים */
function cleanMayaNote(raw) {
  let s = String(raw || '').replace(/\s+/g, ' ').trim();
  s = s.replace(/^["'״«]+|["'״»]+$/g, '').trim();
  s = s.replace(/\s*[—–]\s*/g, ', ');
  if (s.length > 200) s = `${s.slice(0, 197).trim()}…`;
  return s;
}

module.exports = { buildMayaNotePrompt, cleanMayaNote, SCREEN_HINT };
