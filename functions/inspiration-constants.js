function anglesFromQuery(query) {
  const q = String(query || '').toLowerCase();
  if (!q.trim()) return [];
  const hits = [];
  for (const [angle, words] of Object.entries(ANGLE_QUERY_WORDS)) {
    if (words.some((w) => q.includes(w))) hits.push(angle);
  }
  return hits;
}

