/** התמונות שלה, כדי שהפירוק ידע על מה הוא יכול להסתמך */
function assetsBlock(assets) {
  const list = Array.isArray(assets) ? assets.filter(Boolean).slice(0, 60) : [];
  if (!list.length) {
    return `
# התמונות שלה
אין לה עדיין תמונות בתיקייה. לכן בשדה asset כותבים מה צריך במילים, למשל
"רקע נקי" או "B-roll שלך עורכת", ולא מפנים לתמונה ספציפית.`;
  }
  const byKind = { bg: [], portrait: [], both: [] };
  list.forEach((a) => {
    const kind = byKind[a.kind] ? a.kind : 'both';
    byKind[kind].push(a.title || a.name || 'תמונה');
  });
  return `
# התמונות שכבר יש לה בתיקייה
רקעים נקיים: ${byKind.bg.length ? byKind.bg.join(', ') : 'אין'}
תמונות תדמית: ${byKind.portrait.length ? byKind.portrait.join(', ') : 'אין'}
תדמית שאפשר גם כרקע: ${byKind.both.length ? byKind.both.join(', ') : 'אין'}

בשדה asset אפשר להפנות לאחת מהן בשמה, או לכתוב מה צריך במילים כשאין מתאימה.`;
}

