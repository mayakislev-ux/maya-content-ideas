/** התמונות שלה, כדי שהפירוק ידע על מה הוא יכול להסתמך */
function assetsBlock(assets) {
  const list = Array.isArray(assets) ? assets.filter(Boolean).slice(0, 60) : [];
  if (!list.length) {
    return `
# התמונות שלה
אין לה עדיין תמונות בתיקייה. בשדה asset לכתוב מה צריך במילים, או placeholder
בסוגריים מרובעים כשנדרש נכס אמיתי.`;
  }
  const byKind = { bg: [], portrait: [], both: [] };
  list.forEach((a) => {
    const kind = byKind[a.kind] ? a.kind : 'both';
    byKind[kind].push(a.title || a.name || 'תמונה');
  });
  return `
# התמונות שכבר יש לה בתיקייה
רקעים נקיים: ${byKind.bg.length ? byKind.bg.join(', ') : 'אין'}
תמונות תדמית: ${byKind.portrait.length ? byKind.portrait.join(', ') : 'אין'}
תדמית שאפשר גם כרקע: ${byKind.both.length ? byKind.both.join(', ') : 'אין'}

אפשר להפנות לאחת מהן בשמה, או לכתוב מה צריך במילים.`;
}

const GOAL_NAMES = [
  'חוק השתקפות', 'מודעות לבעיה', 'מודעות לפתרון', 'שבירת אמונה',
  'שריפת גשר', 'ביקורת מקצועית', 'סמכות', 'בידול', 'חיבור אישי',
  'הוכחה', 'מכירה',
];

const SLIDE_JOBS = [
  'HOOK', 'MIRROR', 'TENSION', 'COST', 'ROOT', 'REFRAME', 'PROOF',
  'MECHANISM', 'SOLUTION', 'OFFER', 'CTA', 'LANDING',
];

function buildStorySequencePrompt({
  topic, context, cta, assets, corrections = '', goal = 'auto',
} = {}) {
  const extra = context ? `\nמידע נוסף שהיא נתנה: ${context}` : '';
  const ctaLine = cta
    ? `\nCTA רצוי: ${cta}. לסיים בו רק אם הרצף באמת הכין אותו.`
    : '\nלא ניתן CTA. להוסיף אותו רק אם הוא הצעד ההגיוני הבא, ואחרת לוותר.';
  const goalLine = GOAL_NAMES.includes(goal)
    ? `\nהמטרה נקבעה מראש: **${goal}**. לבנות לפיה.`
    : '\nהמטרה לא נקבעה. לבחור אותה לפי עץ ההחלטה ולכתוב אותה בשדה @@GOAL.';
  const fix = corrections ? `\n\n# תיקונים לתשובה הקודמת\n${corrections}` : '';

  return `${IDENTITY}

${AB}

${GOALS}

${JOBS}

${FORMATS}

${LANGUAGE}

${LENGTH}

${SINS}

${QA}

${assetsBlock(assets)}

# הקלט

רעיון: ${topic}${extra}${goalLine}${ctaLine}${fix}

# הפלט

להשיב אך ורק בפורמט הבא, בלי טקסט לפני או אחרי, ובלי code fences. זה אינו
JSON ולכן מרכאות, אימוג'ים, חצים ושורות חדשות מותרים חופשי:

@@GOAL <אחת מהמטרות שלמעלה>
@@A <מה הקהל חושב היום, משפט אחד>
@@B <מה הוא יחשוב אחרי, משפט אחד>
@@WHY <המחיר או הטוויסט המרכזי, משפט אחד או שניים>
@@STORY 1
@job <אחד מ-${SLIDE_JOBS.join(' / ')}>
@role <שם קצר לתפקיד בעברית, למשל עצירה / שיקוף>
@format <הפורמט במשפט אחד>
@asset <ויזואל שצריך, או placeholder בסוגריים מרובעים, או ריק בדיבור למצלמה>
@poll <אפשרות | אפשרות. רק אם הסקר עושה עבודה, אחרת להשמיט>
@note <הערת בימוי, או להשמיט>
@text
<הטקסט שעל המסך, בדיוק כפי שיופיע, עם שבירות שורה>
@speech
<מה להגיד למצלמה. בסטורי של טקסט להשמיט את השדה>
@small
<השורה הקטנה, רק בסטורי האחרון>
@@STORY 2
...
@@END

כל שדה מתחיל ב-@ בתחילת שורה. @text, @speech ו-@small לוקחים את כל השורות
שאחריהם. שדה בלי תוכן להשמיט לגמרי.

כללים קשיחים:
- בין 2 ל-7 סטוריז, והמספר המינימלי שמספיק
- @@GOAL, @@A, @@B ו-@@WHY חייבים להופיע
- לכל סטורי JOB אחד, והאחרון הוא LANDING
- פונים ב"אתם", אף פעם לא ב"את" או "אתה"
- ברצף של 5 ומעלה, עד שני סטוריז של דיבור למצלמה, ולא שניים ברצף
- לכל סטורי או @text או @speech, אף פעם לא שניהם חסרים
- אין להעתיק משפט מהדוגמאות שבפרומפט`;
}

