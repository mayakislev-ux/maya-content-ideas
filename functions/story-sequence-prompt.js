/** חלק המילים המשותפות מתוך הקצר מבין השניים */
function wordOverlap(a, b) {
  if (!a.length || !b.length) return 0;
  const bag = new Map();
  a.forEach((w) => bag.set(w, (bag.get(w) || 0) + 1));
  let hits = 0;
  b.forEach((w) => {
    const left = bag.get(w) || 0;
    if (left > 0) { bag.set(w, left - 1); hits += 1; }
  });
  return hits / Math.min(a.length, b.length);
}

