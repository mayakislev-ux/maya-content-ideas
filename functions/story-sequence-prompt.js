/**
 * בדיקת הרצף מול הכללים שאפשר לבדוק מכנית.
 *
 * רק כללים חד משמעיים. איכות הכתיבה אינה נבדקת כאן, ובמיוחד לא "האם זה
 * מעניין". הבדיקה קיימת כי הפרומפט לבדו לא החזיק שלוש פעמים.
 */

/* משפטים מהדוגמאות של מאיה. כשהם מופיעים בתשובה, המודל שכפל דוגמה על נושא
   אחר במקום לבנות מהמנגנון, וזה מה שגרם ל"שפה מוזרה". */
const BORROWED = [
  'כנראה שהקהל שלי פשוט לא מגיב',
  'קהל שלא מגיב',
  'אפילו לא איזה אימוג',
  'מופנמות היא אופי',
  'ממומן הוא מגבר',
  'איכות הפקה לא מפצה',
  'קניתם תאורה',
  'הייתי 4 חודשים בסוכנות',
];

/** קלישאות שמאיה מסווגת כשפה אוטומטית */
const CLICHES = ['אם גם אתם', 'האמת היא', 'ופה בדיוק', 'בואו נדבר על', 'בעולם של היום'];

/** פנייה ברבים, כמו בכל הדוגמאות שלה */
function addressesPlural(text) {
  return /אתם|אתכם|שלכם|אליכם|לכם|תם\b|ים\b|ות\b/.test(String(text || ''));
}

function checkSequence(stories, meta) {
  const list = Array.isArray(stories) ? stories : [];
  const info = meta && typeof meta === 'object' ? meta : {};
  const problems = [];
  const body = (s) => `${(s && s.text) || ''} ${(s && s.speech) || ''} ${(s && s.small) || ''}`;

  if (list.length < 2 || list.length > 7) {
    problems.push(`צריך בין 2 ל-7 סטוריז, יש ${list.length}.`);
  }

  if (!String(info.goal || '').trim()) problems.push('חסרה המטרה. בלי סיווג אין מבנה.');
  else if (!GOAL_NAMES.includes(String(info.goal).trim())) {
    problems.push(`"${info.goal}" אינה אחת מ-11 המטרות.`);
  }
  if (!String(info.a || '').trim()) problems.push('חסר A, מה הקהל חושב היום.');
  if (!String(info.b || '').trim()) problems.push('חסר B, מה הוא יחשוב אחרי.');

  const unknownJob = list.find((s) => s && s.job && !SLIDE_JOBS.includes(String(s.job).toUpperCase()));
  if (unknownJob) problems.push(`"${unknownJob.job}" אינו תפקיד שקופית מוכר.`);
  const noJob = list.findIndex((s) => !(s && s.job));
  if (noJob > -1) problems.push(`לסטורי ${noJob + 1} אין תפקיד. לכל שקופית JOB אחד.`);

  const last = list[list.length - 1];
  if (list.length && last && String(last.job || '').toUpperCase() !== 'LANDING') {
    problems.push('הסטורי האחרון אינו LANDING. הוא המשפט שנשאר בראש.');
  }

  const first = list[0] || {};
  const firstText = body(first);
  if (/מישהי ש|מישהו ש|ראיתי את זה|אני רואה את זה/.test(firstText)) {
    problems.push('סטורי 1 מסופר על מישהו אחר או מכיסא המאבחנת. לתאר את הסצנה שלהם בהווה.');
  }
  /* 02/10/2026: הכלל הזה שייך למטרות שבהן סטורי 1 הוא הסצנה שלהם. בביקורת
     מקצועית, שריפת גשר או סמכות, סטורי 1 הוא ההצהרה או הסיפור שלה, ואז
     הדרישה לפנייה ברבים היא אזעקת שווא שגררה קריאה שנייה שלמה ל-AI ועוד
     תשעים שניות המתנה. */
  const SCENE_GOALS = ['חוק השתקפות', 'מודעות לבעיה'];
  if (SCENE_GOALS.includes(String(info.goal || '').trim())
    && firstText.trim() && !addressesPlural(firstText)) {
    problems.push('סטורי 1 אינו פונה ב"אתם". בשיקוף הפנייה תמיד ברבים.');
  }

  const whole = list.map(body).join(' ');
  const borrowed = BORROWED.find((t) => whole.includes(t));
  if (borrowed) {
    problems.push(`הרצף מעתיק משפט מדוגמה על נושא אחר ("${borrowed}"). כל משפט נגזר מהנושא שניתן.`);
  }
  const cliche = CLICHES.find((t) => whole.includes(t));
  if (cliche) problems.push(`"${cliche}" היא שפה אוטומטית. לנסח אחרת.`);

  const speechFlags = list.map((s) => Boolean(s && s.speech));
  const speechCount = speechFlags.filter(Boolean).length;
  if (list.length >= 5 && speechCount > 2) {
    problems.push(`ברצף של ${list.length} מותר עד שני דיבורים למצלמה, יש ${speechCount}.`);
  }
  for (let i = 1; i < speechFlags.length; i++) {
    if (speechFlags[i] && speechFlags[i - 1]) {
      problems.push('יש שני דיבורים למצלמה ברצף. צריך להפריד ביניהם.');
      break;
    }
  }

  const empty = list.findIndex((s) => !(s && (s.text || s.speech)));
  if (empty > -1) problems.push(`סטורי ${empty + 1} ריק, אין בו טקסט ולא דיבור.`);

  return problems;
}

module.exports = { buildStorySequencePrompt, checkSequence, GOAL_NAMES, SLIDE_JOBS };
