/**
 * בדיקת הרצף מול הכללים שאפשר לבדוק מכנית.
 *
 * 02/10/2026: הפרומפט לבדו לא החזיק פעמיים. לכן אחרי כל תשובה נבדקים הכללים
 * שאפשר לקבוע עליהם חד משמעית, ואם משהו הופר יוצאת בקשה נוספת עם התיקון.
 * רק כללים חד משמעיים. איכות הכתיבה אינה נבדקת כאן.
 */
const SOLUTION_HINTS = [
  'ולכן', 'הסיבה היא', 'מה שבאמת', 'הטעות היא', 'לא מבינה למה',
  'לא מבינים למה', 'זה לא עובד כי', 'הפתרון',
];

/* 02/10/2026: המודל העתיק משפטים שלמים מהדוגמאות שבפרומפט לתוך נושא אחר
   לגמרי. "טוב, כנראה שהקהל שלי פשוט לא מגיב" הוא מדוגמה על סטוריז שלא
   מקבלים תגובות, והוא הופיע ברצף על זה שלא יודעים למה תוכן מצליח. מאיה:
   "רצף סטוריז מוזר, בשפה מוזרה". אלה המשפטים שאסור שיחזרו. */
const BORROWED = [
  'כנראה שהקהל שלי פשוט לא מגיב',
  'קהל שלא מגיב',
  'אפילו לא איזה אימוג',
  'מופנמות היא אופי',
  'ממומן הוא מגבר',
  'איכות הפקה לא מפצה',
  'קניתם תאורה',
  'הייתי 4 חודשים בסוכנות',
];

/* 02/10/2026: "איך לעשות את זה" ו"הדרך לעשות" הם צירופים יומיומיים שמופיעים
   גם בשיקוף תמים, והם ירו אזעקת שווא שגררה קריאה שנייה שלמה ל-AI ובגללה
   נגמר הזמן אצל מאיה. נשארו רק ציוויים חד משמעיים. */
const ADVICE_HINTS = [
  'כדאי לכם', 'תתחילו ל', 'תנסו ל', 'הנה כמה', 'הנה 3', 'הנה 5',
  'הדרך הנכונה היא', 'מה שצריך לעשות זה',
];

/** פנייה ברבים, כמו בכל ארבע הדוגמאות שלה */
function addressesPlural(text) {
  return /אתם|אתכם|שלכם|אליכם|לכם|תם\b|ים\b|ות\b/.test(String(text || ''));
}

function checkSequence(stories, job) {
  const list = Array.isArray(stories) ? stories : [];
  const problems = [];
  /* 02/10/2026: שני טיפוסי רצף, ולכן שתי מערכות כללים. מחיר נדרש בשיקוף
     בלבד, שיתוף אישי וקריטריון נדרשים בעמדה בלבד, ומסקנה מוטעית אסורה
     בעמדה כי שם הצופה הוא קונה שבוחר ולא נכשל. */
  const kind = job || (Array.isArray(stories) && stories.job) || 'mirror';
  const all = (s) => `${(s && s.role) || ''} ${(s && s.text) || ''} ${(s && s.speech) || ''} ${(s && s.note) || ''}`;

  if (list.length < 5 || list.length > 6) {
    problems.push(`צריך 5 עד 6 סטוריז, יש ${list.length}.`);
  }

  const first = list[0] || {};
  const firstText = `${first.text || ''} ${first.speech || ''}`;

  if (/מישהי ש|מישהו ש|ראיתי את זה|אני רואה את זה/.test(firstText)) {
    problems.push(
      'סטורי 1 מסופר על מישהו אחר או מכיסא המאבחנת. צריך לתאר את הסצנה שלהם ' +
      'בהווה ובגוף שני רבים, או לפתוח בוידוי אישי שלך.'
    );
  }
  const hint = SOLUTION_HINTS.find((h) => firstText.includes(h));
  if (hint) {
    problems.push(`סטורי 1 כבר מסיק מסקנה ("${hint}"). הוא צריך לתאר בלבד ולהיגמר בלי לסגור.`);
  }
  /* בעמדה סטורי 1 הוא ההצהרה שלה ולא הסצנה שלהם, ולכן הוא אינו חייב
     להיות בגוף שני. בשיקוף הוא כן. */
  if (kind === 'mirror' && firstText.trim() && !addressesPlural(firstText)) {
    problems.push('סטורי 1 אינו פונה ב"אתם". הפנייה תמיד ברבים, "אתם מעלים", "קניתם".');
  }
  if (first.small) {
    problems.push('לסטורי 1 יש שורה קטנה. השורה הקטנה שייכת למסר האחרון בלבד.');
  }

  /* 02/10/2026 (מאיה): "קודם כל שיקוף, לא ישר הנה 5 טיפים". שלושת הראשונים
     הם שיקוף בלבד, ואסור שתיכנס אליהם עצה. */
  list.slice(0, 3).forEach((s, i) => {
    const body = `${(s && s.text) || ''} ${(s && s.speech) || ''}`;
    const advice = ADVICE_HINTS.find((h) => body.includes(h));
    if (advice) {
      problems.push(`סטורי ${i + 1} נותן עצה ("${advice}"). שלושת הראשונים הם שיקוף בלבד.`);
    }
  });

  /* משפט שאול מדוגמה אחרת, שזה מה שגרם ל"שפה מוזרה" */
  const whole = list.map((s) => `${(s && s.text) || ''} ${(s && s.speech) || ''} ${(s && s.small) || ''}`).join(' ');
  const borrowed = BORROWED.find((t) => whole.includes(t));
  if (borrowed) {
    problems.push(
      `הרצף מעתיק משפט מדוגמה על נושא אחר ("${borrowed}"). כל משפט חייב לנבוע מהנושא שניתן.`
    );
  }

  if (kind === 'mirror') {
    /* המחיר הוא שליש מהרצף אצלה, ובלעדיו הוא נכון אבל לא כואב */
    const hasPrice = list.some((s) => /מחיר|בפועל|מה זה אומר/.test(all(s)));
    if (list.length && !hasPrice) {
      problems.push('אין פעימה שנושאת את המחיר. צריך לתרגם את הבעיה לתוצאה עסקית על ציר זמן.');
    }
  } else {
    const hasPersonal = list.some((s) => /שיתוף אישי|הסיפור שלי|אני התחלתי|הייתי צריכה|בעסק שלי/.test(all(s)));
    if (list.length && !hasPersonal) {
      problems.push('בעמדה חסר השיתוף האישי. ההוכחה היא העבודה שלך, לא התוצאות שלך.');
    }
    const hasCriterion = list.some((s) => /קריטריון|תשאלו|לבדוק|מה שצריך לחפש|האם הוא/.test(all(s)));
    if (list.length && !hasCriterion) {
      problems.push('בעמדה חסר הקריטריון. הצופה צריך לצאת עם שאלה לשאול את השוק.');
    }
    const victim = list.find((s) => /כנראה שאני פשוט|כנראה שאני לא|אני לא מיועד/.test(all(s)));
    if (victim) {
      problems.push('בעמדה אין מסקנה מוטעית ואין קורבן. הצופה הוא קונה שבוחר, לא נכשל.');
    }
  }

  const speechFlags = list.map((s) => Boolean(s && s.speech));
  const speechCount = speechFlags.filter(Boolean).length;
  if (speechCount !== 2) {
    problems.push(`צריך בדיוק שני סטוריז של דיבור למצלמה, יש ${speechCount}.`);
  }
  for (let i = 1; i < speechFlags.length; i++) {
    if (speechFlags[i] && speechFlags[i - 1]) {
      problems.push('יש שני דיבורים למצלמה ברצף. צריך להפריד ביניהם.');
      break;
    }
  }

  const empty = list.findIndex((s) => !(s && (s.text || s.speech)));
  if (empty > -1) problems.push(`סטורי ${empty + 1} ריק, אין בו טקסט ולא דיבור.`);

  const last = list[list.length - 1] || {};
  if (list.length && !last.small) {
    problems.push('לסטורי האחרון חסרה השורה הקטנה מתחת למסר.');
  }
  if (last.speech) {
    problems.push('הסטורי האחרון הוא דיבור למצלמה. המסר שנשאר בראש הוא טקסט על רקע נקי.');
  }

  return problems;
}

/**
 * מנקה מסגור שהמודל מדביק לתוך השדה.
 *
 * 02/10/2026: שדות חזרו עם מילות ההוראה בתוכם. ניקוי בקוד עובד תמיד, גם
 * כשהמודל מתעקש.
 */
const FRAMING = [
  /^\s*הגשר שאת רוצה לשרוף הוא\s*:?\s*/,
  /^\s*הניסוח הגס\s*:?\s*/,
  /^\s*המסר הגס\s*:?\s*/,
  /^\s*לא\s*:\s*/,
  /^\s*כן\s*:\s*/,
];

function stripFraming(value) {
  let out = String(value == null ? '' : value).trim();
  let changed = true;
  while (changed) {
    changed = false;
    for (const re of FRAMING) {
      if (re.test(out)) { out = out.replace(re, ''); changed = true; }
    }
    const quoted = out.match(/^['"“”‘’](.*)['"“”‘’]$/s);
    if (quoted) { out = quoted[1].trim(); changed = true; }
  }
  return out.trim();
}

module.exports = { buildStorySequencePrompt, stripFraming, checkSequence };
