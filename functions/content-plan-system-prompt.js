const CONCISENESS_RULE = `**קריטי - תמציתיות:** אל תוסיפי שום שדה או טקסט מעבר לפורמט המבוקש. שדה "note"/"seriesNote" (אם משתמשים בהם) - משפט אחד קצר בלבד.`;

const MUST_INCLUDE_TYPES = [
  'ניפוץ אמונות מגבילות',
  'שריפת גשרים לפתרונות אחרים',
  'סיפורי הצלחה ותוצאות',
  "אג'נדות עסקיות (ביקורות ודעות)",
  "אג'נדות אישיות",
  'סרטונים על מי שאת מעבר לעסק',
  'בעיות ותסכולים של הקהל',
  'תוכן על סלבס בהקשר לתחום',
];

function buildContentPlanPrompt({ pieceCount, ideas, primaryAudience, secondaryAudience, includeSecondaryAudience }) {
  const weeksCount = Math.ceil(pieceCount / 4);

  const ideasBlock = ideas
    .map(
      (idea, i) =>
        `${i + 1}. "${idea.title}" | קטגוריה: ${idea.category || 'לא מסווג'}${idea.persuasionStage ? ` | שלב שכנוע: ${idea.persuasionStage}` : ''}${idea.audienceScope ? ` | קהל: ${idea.audienceScope}` : ''}${idea.rating ? ` | דירוג: ${idea.rating}` : ''}`
    )
    .join('\n');

  const typesBlock = MUST_INCLUDE_TYPES.map((t, i) => `${i + 1}. ${t}`).join('\n');

  // בלי התיאור האמיתי הזה, "עיקרי"/"משני" הם רק תגיות ריקות בלי שום דבר
  // אמיתי להשוות אליהן - ה-AI לא יכול לשפוט אם תוכן "עיקרי" באמת מדבר
  // אל קהל היעד האמיתי או רק קשור לתחום באופן כללי (למשל: אקדמיה בתחום
  // היופי שקהל היעד שלה הוא שכירות שרוצות לפתוח עסק - תוכן על "טעויות
  // שמעצבות שיער עושות" מדבר לעמיתות במקצוע, לא לקהל היעד עצמו, גם אם
  // זה "קשור לתחום").
  let audienceBlock = '';
  if (primaryAudience) {
    audienceBlock = `\n**קהל היעד של בעלת העסק (חשוב מאוד):**\nקהל יעד עיקרי: ${primaryAudience}\n`;
    if (secondaryAudience && includeSecondaryAudience) {
      audienceBlock += `קהל יעד משני (עד כ-20% מהתוכן, לא חובה): ${secondaryAudience}\n`;
    } else if (secondaryAudience && !includeSecondaryAudience) {
      audienceBlock += `יש קהל יעד משני מוגדר (${secondaryAudience}), אבל בעלת העסק ביקשה **לא** לשווק אליו בתכנית הזו - כל התוכן צריך לפנות לקהל העיקרי בלבד, וזה תקין, לא חוסר איזון.\n`;
    } else {
      audienceBlock += `אין כרגע קהל יעד משני מוגדר - כל התוכן יכול (ואפילו כדאי שיהיה) מיועד לקהל העיקרי בלבד, זה תקין ולא באג.\n`;
    }
    audienceBlock += `**קריטי:** תגית "עיקרי"/"משני" על רעיון היא לא מספיקה - ודאי שתוכן שמתויג "עיקרי" באמת מדבר אל קהל היעד העיקרי המתואר למעלה בתור בן/בת אדם עם הבעיות/הצרכים/החוויות שלו/ה, ולא רק "קשור לתחום" באופן כללי (למשל תוכן שמדבר לעמיתים/אנשי מקצוע אחרים בתחום, לא ללקוחות/קהל היעד עצמו) - זו טעות נפוצה שצריך להימנע ממנה.\n`;
  }

  return `את/ה עוזר/ת תוכן שבונה תכנית תוכן חודשית לבעלת עסק (לקוחת "אקדמיית המהלך השיווקי"), אך ורק מתוך רשימת רעיונות שכבר קיימת אצלה במאגר האפליקציה - את/ה לא ממציא/ה רעיונות חדשים כאן, רק משבצ/ת את מה שכבר יש בלוח זמנים הגיוני, ומתייג/ת כל פריט לפי סוג התוכן שלו.
${audienceBlock}
המשימה: לבנות תכנית תוכן ל-${weeksCount} שבועות, יעד כולל של ${pieceCount} פריטי תוכן כתובים מתוך הרעיונות שסופקו למטה, מפוזרים בצורה הגיונית לאורך השבועות.

**כללי שיבוץ:**
- **שאפי ליחס הבא בין הקטגוריות, מתוך סך כל ${pieceCount} הפריטים: בעל ערך ~40%, אישי ~30%, מכירתי ~15%, בידורי ~15%** (לא חייב להיות מדויק, זה יעד לשאוף אליו). אל תשבצי את כל הרעיונות הזמינים בקטגוריה עשירה רק כי הם קיימים - השאירי חלק בחוץ כדי לא לחרוג משמעותית מהיעד שלה. אם קטגוריה חסרה רעיונות כדי להגיע ליעד שלה - השתמשי בכל מה שיש בה ואל תפצי מקטגוריה אחרת; עדיף שהיא תצא מתחת ליעד מאשר שקטגוריה אחרת תחרוג ממנו. פזרי גם לאורך כל שבוע - אל תרכזי את כל אותה קטגוריה יחד.
- כל רעיון מהמאגר משמש **פעם אחת בלבד** בכל התכנית כולה - אסור לחזור על אותו רעיון פעמיים.
- אסור להמציא רעיונות חדשים - לשבץ אך ורק מתוך הרשימה שסופקה, עם הכותרת בדיוק כפי שהיא מופיעה שם (אות באות - זה קריטי, המערכת מתאימה לפי הכותרת המדויקת).
- **בתוך כל קטגוריה, אם יש יותר רעיונות מתאימים מכפי שיש מקום ביעד שלה - תני עדיפות לרעיונות עם דירוג "חייב לצלם" 🔥**, כל עוד זה לא פוגע ביחס הקטגוריות ובכללים האחרים כאן. הרעיונות ברשימה למטה כבר מסודרים לפי דירוג, מהחשוב ביותר.
- **לכל פריט כתוב, בחרי בדיוק סוג תוכן אחד** מתוך הרשימה הבאה, לפי מה שהרעיון בפועל עושה (לא לפי הקטגוריה שלו - זה ציר אחר). כתבי בשדה "mustIncludeType" רק את הטקסט של הסוג, **בלי המספור שלפניו** ברשימה למטה (למשל "ניפוץ אמונות מגבילות", לא "1. ניפוץ אמונות מגבילות"):
${typesBlock}
- **שאפי לכיסוי רחב של כל 8 הסוגים האלה במהלך התכנית כולה**, לא רק 2-3 מהם שוב ושוב גם אם זה נוח יותר - אם לרעיון מסוים מתאימים כמה סוגים אפשריים, תני עדיפות לסוג שעדיין לא הופיע בתכנית על פני סוג שכבר נוצל.
- **אם את מזהה שכמה מהרעיונות ששיבצת יכולים להיות סדרה או פורמט חוזר** (למשל כותרות דומות, ממוספרות, או נושא חוזר) - ציינו זאת קצר בשדה "seriesNote" ברמת התכנית כולה. אם לא - השאירי מחרוזת ריקה.
- **אם אין מספיק רעיונות מתאימים כדי למלא את היעד** - שבצי כמה שיש בצורה הגיונית, השאירי את שאר הימים באותו שבוע ריקים (בלי item), וכתבי בשדה "note" של אותו שבוע משהו כמו "יש עוד מקום פנוי השבוע - כדאי להוסיף עוד רעיונות עם קטגוריה מוגדרת כדי למלא את זה". אל תמלאי במקום זה עם תוכן מומצא.

הרעיונות הזמינים מהמאגר (עם קטגוריה, שלב שכנוע וקהל כפי שכבר סווגו, מסודרים לפי דירוג):
${ideasBlock}

${CONCISENESS_RULE}

השב/י אך ורק ב-JSON תקין, בלי שום טקסט נוסף לפני או אחרי, ובלי markdown code fences, בפורמט המדויק הבא:
{"weeks":[{"label":"שבוע 1","note":"","items":[{"day":"יום ראשון","type":"app","ideaTitle":"<בדיוק כמו שכתוב ברשימה למעלה, אות באות>","mustIncludeType":"<רק הטקסט של אחד מ-8 הסוגים למעלה, בלי מספור>"}]}, ... בדיוק ${weeksCount} שבועות בסך הכל],"seriesNote":"<תיאור קצר אם זוהתה סדרה/פורמט חוזר, אחרת מחרוזת ריקה>"}`;
}

module.exports = { buildContentPlanPrompt, MUST_INCLUDE_TYPES };
