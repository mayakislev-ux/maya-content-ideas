import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseOptions } from '../js/va-smart-paste.js';

test('רשימה ממוספרת עם פתיח וסיום: רק האפשרויות, בלי הפתיח ובלי השאלה בסוף', () => {
  const answer = `הנה 5 הוקים באותו מנגנון:

1. למה הלקוחות שלך לא חוזרות אחרי טיפול אחד?
2. הטעות שעולה לך שלוש לקוחות בחודש
3. אף אחד לא מספר לך את זה על גבות
4. **זה לא המכשיר, זה מה שקורה אחרי**
5. "שלוש שאלות לפני שקובעים תור"

רוצה שאכין עוד גרסאות?`;
  assert.deepEqual(parseOptions(answer), [
    'למה הלקוחות שלך לא חוזרות אחרי טיפול אחד?',
    'הטעות שעולה לך שלוש לקוחות בחודש',
    'אף אחד לא מספר לך את זה על גבות',
    'זה לא המכשיר, זה מה שקורה אחרי',
    'שלוש שאלות לפני שקובעים תור',
  ]);
});

test('1) ו-1- ו-(1) הם גם מספור', () => {
  assert.deepEqual(parseOptions('1) אחד\n2) שתיים'), ['אחד', 'שתיים']);
  assert.deepEqual(parseOptions('1- אחד\n2- שתיים'), ['אחד', 'שתיים']);
  assert.deepEqual(parseOptions('(1) אחד\n(2) שתיים'), ['אחד', 'שתיים']);
});

test('תבליטים: - ו-•', () => {
  assert.deepEqual(parseOptions('- אחד\n- שתיים\n- שלוש'), ['אחד', 'שתיים', 'שלוש']);
  assert.deepEqual(parseOptions('• אחד\n• שתיים'), ['אחד', 'שתיים']);
});

test('מספור עברי: א. ב. ג. וגם א) ב)', () => {
  assert.deepEqual(parseOptions('א. ראשון\nב. שני\nג. שלישי'), ['ראשון', 'שני', 'שלישי']);
  assert.deepEqual(parseOptions("א) ראשון\nב) שני"), ['ראשון', 'שני']);
});

test('אפשרות על כמה שורות, עם תבליטים פנימיים: נשארת אפשרות אחת', () => {
  const answer = `1. **כיוון: "יום בחיים"**
   - מראים בוקר רגיל במספרה
   - ובסוף חושפים את הטעות
2. **כיוון: "שאלה מהתיבה"**
   - עונים על שאלה אמיתית`;
  const out = parseOptions(answer);
  assert.equal(out.length, 2);
  assert.match(out[0], /^כיוון: "יום בחיים"\n- מראים בוקר רגיל במספרה\n- ובסוף חושפים את הטעות$/);
  assert.equal(out[1], 'כיוון: "שאלה מהתיבה"\n- עונים על שאלה אמיתית');
});

test('הסבר בפסקה נפרדת מתחת לכל כיוון נשאר עם הכיוון שלו, והסיום לא נדבק לאחרון', () => {
  const answer = `1. הלקוחה שחזרה אחרי שנה

מספרים את הסיפור מהצד שלה.

2. המיתוס על חומרים זולים

מפרקים את המיתוס במשפט אחד.

איזה כיוון הכי מדבר אלייך?`;
  assert.deepEqual(parseOptions(answer), [
    'הלקוחה שחזרה אחרי שנה\n\nמספרים את הסיפור מהצד שלה.',
    'המיתוס על חומרים זולים\n\nמפרקים את המיתוס במשפט אחד.',
  ]);
});

test('כותרות קבוצה בין האפשרויות לא נדבקות לאפשרות שלפניהן', () => {
  const answer = `**הוקים של סקרנות**
1. אחד
2. שתיים

**הוקים של כאב**
3. שלוש
4. ארבע`;
  assert.deepEqual(parseOptions(answer), ['אחד', 'שתיים', 'שלוש', 'ארבע']);
});

test('פחות משתי אפשרויות: ריק, והמסך מתנהג בדיוק כמו קודם', () => {
  assert.deepEqual(parseOptions(''), []);
  assert.deepEqual(parseOptions('הוק אחד בלבד שהודבק'), []);
  assert.deepEqual(parseOptions('1. רק אחד'), []);
  assert.deepEqual(parseOptions('משפט ראשון.\nמשפט שני.\nמשפט שלישי.'), []);
});

test('30 הוקים: כל ה-30, גם מספרים דו-ספרתיים', () => {
  const answer = Array.from({ length: 30 }, (_, i) => `${i + 1}. הוק מספר ${i + 1}`).join('\n');
  const out = parseOptions(answer);
  assert.equal(out.length, 30);
  assert.equal(out[29], 'הוק מספר 30');
});
